/**
 * 길찾기(RideNav) 전용 — 내 위치 마커의 "위에서 본 오토바이" 실루엣.
 *
 * 왜 별도 모듈인가: 소비자인 MapCanvas 의 `headingEl()` 은 React 가 아니라 DOM 을 직접 만드는
 * 함수라 JSX 컴포넌트(`maps/compassIcons.tsx`)를 쓸 수 없다. 그래서 `innerHTML` 에 그대로 꽂는
 * **문자열 상수**로 둔다. `maps/` 가 아니라 `ride/` 에 두는 이유는 이 마커가 길찾기 전용이기
 * 때문 — 동네지도(SaigonMapV5)의 내 위치 점·heading 삼각형은 탐색용이라 역할이 다르고, 대표
 * 결정으로 이번 범위에서 제외됐다(공유 자산으로 올리면 그 경계가 흐려진다).
 *
 * 형태 결정 (2026-08-07, 1x 격리 렌더 비교 후):
 * - **남긴 것** — ① 앞바퀴/펜더를 삼각형 코로, ② 핸들바 가로바, ③ 뒤로 갈수록 넓어지는 몸통,
 *   ④ 짧은 뒷바퀴 꼬리. 이 넷이 22~32px 에서 살아남는 유일한 단서다.
 * - **버린 것** — 미러 볼(끝에 원을 달면 "뿔/안테나"로 읽혔다), 엔진·머플러·라이더 디테일,
 *   앞바퀴를 사각으로 그리는 안(가로바 위 세로바 = 십자가로 읽혀 앞뒤가 사라졌다).
 * - **앞뒤 비대칭** — 위에서 본 오토바이는 좌우대칭이라 방향이 약하다. 그래서 앞은 뾰족한 코가
 *   가로바 밖으로 튀어나오게, 뒤는 넓은 시트 + 가는 꼬리로 만들어 "화살촉 → 몸통" 순서가 되게 했다.
 *   1x 에서 차종은 못 읽혀도 **어디가 앞인지는 읽힌다** — 방향 표시가 목적이므로 이 우선순위가 맞다.
 * - 대비 전략은 기존 dot(#2563EB + 흰 테두리 + 그림자)을 계승한다. 다만 실루엣이라 테두리를
 *   그릴 수 없어, 같은 도형을 흰색으로 굵게 한 번 깔고(할로) 그 위에 파란색을 덮는 2-pass 로 낸다
 *   (도형별 stroke 를 쓰면 겹치는 부분에 흰 선이 생긴다).
 * - 크기 30px — 22px 는 코·가로바가 뭉개졌고 34px 는 지도를 가린다. 가로바 두께는 3.5u(≈3.3px)
 *   — 2.9u(≈2.7px)로 뽑았을 때 사선 회전에서 안티에일리어싱에 먹혀 몸통에 붙어버렸다(1x 확인).
 *
 * 회전 0° = 진북(위쪽)을 향한다. 회전은 MapLibre Marker 의 `setRotation()` 이 건다(MapCanvas 참조).
 */

/** 마커 한 변(px). 회전해도 잘리지 않도록 wrap 도 이 크기의 정사각형. */
export const RIDER_MARKER_PX = 30;

/** viewBox 32×32 기준 실루엣. 흰 할로 pass 와 파란 fill pass 가 같은 도형을 공유한다. */
const SHAPES =
  '<path d="M16 1.4 19.8 7.2h-7.6Z"/>' + // 앞바퀴/펜더 — 삼각 코가 "앞"을 만든다
  '<rect x="7.4" y="6.6" width="17.2" height="3.5" rx="1.75"/>' + // 핸들바
  '<path d="M13.6 8.6h4.8l1.3 6.2 3 4.5a6.2 6.2 0 0 1-12.4 0l3-4.5Z"/>' + // 목 → 시트(뒤로 넓어짐)
  '<rect x="14.6" y="22.1" width="2.8" height="6.8" rx="1.4"/>'; // 뒷바퀴 꼬리

export const RIDER_MARKER_SVG =
  `<svg width="${RIDER_MARKER_PX}" height="${RIDER_MARKER_PX}" viewBox="0 0 32 32" aria-hidden="true" ` +
  'style="display:block;filter:drop-shadow(0 1px 2px rgba(0,0,0,.45))">' +
  `<g fill="#fff" stroke="#fff" stroke-width="2.4" stroke-linejoin="round">${SHAPES}</g>` +
  `<g fill="#2563EB">${SHAPES}</g>` +
  '</svg>';
